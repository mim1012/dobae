export const projectPhoto = (id: string, index: number) => photoPaths[`${id}/${index}`];
function gallery(id: string, groups: [PhotoStage, number[], string[]][]): ProjectPhoto[] {
  return groups.flatMap(([stage, indices, captions]) => indices.map((index, i) => ({
    src: projectPhoto(id, index), stage, caption: captions[i], alt: captions[i],
  })));
}

